# -*- coding: utf-8 -*-
import logging

from odoo import http
from odoo.http import request
from odoo.tools import consteq

_logger = logging.getLogger(__name__)


class PaymentRedirectController(http.Controller):
    """
    Controller to handle redirects from payment confirmation page
    back to POS Self Order with proper access token.
    """

    @http.route('/pos-self-order/return-to-order', type='http', auth='public', website=True)
    def return_to_order(self, tx_id=None, token=None, **kwargs):
        """Redirect the payer back to the self-order page of its order.

        The caller must prove it saw the payment confirmation of the
        transaction (``token`` is generated by
        ``payment.transaction._get_pos_self_return_token`` and embedded in
        the confirmation page, which itself requires the transaction access
        token). Only then is the self-order URL of *that* transaction's POS
        config, including its access token, returned. Anything else gets a
        404 and never a pos.config access token.
        """
        try:
            tx_id = int(tx_id)
        except (TypeError, ValueError):
            return request.not_found()
        if not token or not isinstance(token, str):
            return request.not_found()

        tx_sudo = request.env['payment.transaction'].sudo().browse(tx_id).exists()
        if not tx_sudo or not consteq(tx_sudo._get_pos_self_return_token(), token):
            return request.not_found()

        pos_config = tx_sudo.pos_order_id.config_id
        if not pos_config or pos_config.self_ordering_mode not in ('mobile', 'kiosk'):
            _logger.info(
                "No self-ordering POS config linked to transaction %s for payment redirect",
                tx_sudo.id,
            )
            return request.not_found()

        if pos_config.access_token:
            redirect_url = f'/pos-self/{pos_config.id}?access_token={pos_config.access_token}'
        else:
            redirect_url = f'/pos-self/{pos_config.id}/products'

        return request.redirect(redirect_url)
